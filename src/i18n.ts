const enOverrides: Record<string, string> = {
  "Velo": APP_NAME_EN,
  "Velo Mail": APP_NAME_EN,
  "Офис360": APP_NAME_EN,
  "Показать Офис360": `Show ${APP_NAME_EN}`,
  "Эту вкладку можно закрыть и вернуться в Офис360.": `You can close this tab and return to ${APP_NAME_EN}.`,
};

const reverseRu = Object.fromEntries(
  Object.entries(ru).map(([source, translated]) => [translated, source.replaceAll("Velo", APP_NAME_EN)]),
);

function preserveOuterWhitespace(source: string, translated: string) {
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated}${trailing}`;
}

function translatePattern(trimmed: string, locale: AppLocale) {
  if (locale === "ru") {
    const usedMb = trimmed.match(/^(.+) MB used$/);
    if (usedMb) return `Использовано ${usedMb[1]} МБ`;
    const version = trimmed.match(/^Version (.+)$/);
    if (version) return `Версия ${version[1]}`;
    const syncing = trimmed.match(/^Syncing: (.+)\/(.+) messages$/);
    if (syncing) return `Синхронизация: ${syncing[1]}/${syncing[2]} писем`;
    const building = trimmed.match(/^Building threads\.\.\. \((.+)\/(.+)\)$/);
    if (building) return `Сборка цепочек... (${building[1]}/${building[2]})`;
    const failed = trimmed.match(/^Sync failed: (.+)$/);
    if (failed) return `Синхронизация не удалась: ${failed[1]}`;
    const unread = trimmed.match(/^Velo - (.+) unread$/);
    if (unread) return `Офис360 - непрочитанных: ${unread[1]}`;
    const officeUnread = trimmed.match(/^Office360 - (.+) unread$/);
    if (officeUnread) return `Офис360 - непрочитанных: ${officeUnread[1]}`;
    const update = trimmed.match(/^Office360 v(.+) is available$/);
    if (update) return `Доступна версия Офис360 v${update[1]}`;
    const vAvailable = trimmed.match(/^v(.+) available$/);
    if (vAvailable) return `Доступна версия ${vAvailable[1]}`;
    const smtpTestIncomplete = trimmed.match(
      /^SMTP test did not complete within (\d+) seconds\. Check server, port, SSL\/TLS, and auth method\.$/,
    );
    if (smtpTestIncomplete) {
      return `SMTP-проверка не завершилась за ${smtpTestIncomplete[1]} сек. Проверьте сервер, порт, SSL/TLS и способ входа.`;
    }
    const smtpTestTimedOut = trimmed.match(
      /^SMTP test timed out after (\d+) seconds\. Check server, port, SSL\/TLS, and sign-in method\.$/,
    );
    if (smtpTestTimedOut) {
      return `SMTP-проверка не завершилась за ${smtpTestTimedOut[1]} сек. Проверьте сервер, порт, SSL/TLS и способ входа.`;
    }
    const smtpRefused = trimmed.match(
      /^SMTP server (.+):(\d+) refused the TCP connection\. Check port and security type: for Yandex Mail use smtp\.yandex\.ru, port 465, SSL\/TLS\. If settings are correct, the port may be blocked by network, VPN, proxy, or antivirus\.$/,
    );
    if (smtpRefused) {
      return `SMTP-сервер ${smtpRefused[1]}:${smtpRefused[2]} отверг TCP-подключение. Проверьте порт и тип защиты: для Яндекса обычно smtp.yandex.ru, порт 465, SSL/TLS. Если настройки верные, порт блокируется сетью, VPN, прокси или антивирусом.`;
    }
    const inboxCategory = trimmed.match(/^Inbox — (.+)$/);
    if (inboxCategory) return `Входящие — ${translateText(inboxCategory[1] ?? "", locale)}`;
    const conversations = trimmed.match(/^(\d+) conversations?$/);
    if (conversations) {
      const count = Number(conversations[1]);
      const word = count % 10 === 1 && count % 100 !== 11
        ? "переписка"
        : [2, 3, 4].includes(count % 10) && ![12, 13, 14].includes(count % 100)
          ? "переписки"
          : "переписок";
      return `${count} ${word}`;
    }
    const selected = trimmed.match(/^(\d+) selected$/);
    if (selected) return `Выбрано: ${selected[1]}`;
    const noResults = trimmed.match(/^No results for “(.+)”$/);
    if (noResults) return `Ничего не найдено по запросу «${noResults[1]}»`;
    const contactsTotal = trimmed.match(/^(\d+) contacts total$/);
    if (contactsTotal) return `Всего контактов: ${contactsTotal[1]}`;
    const sendersDetected = trimmed.match(/^(\d+) senders detected with unsubscribe headers\.$/);
    if (sendersDetected) return `Найдено отправителей с заголовками отписки: ${sendersDetected[1]}.`;
    const emailsCount = trimmed.match(/^(\d+) emails$/);
    if (emailsCount) return `${emailsCount[1]} писем`;
    const emailCount = trimmed.match(/^(\d+) email$/);
    if (emailCount) return `${emailCount[1]} письмо`;
    const autoArchive = trimmed.match(/^Auto-archive (Updates|Promotions|Social|Newsletters)$/);
    if (autoArchive) return `Автоархивация: ${translateText(autoArchive[1] ?? "", locale)}`;
    const skipInbox = trimmed.match(/^Skip inbox for (updates|promotions|social|newsletters) emails$/);
    if (skipInbox) return `Пропускать входящие для категории «${translateText(skipInbox[1] ?? "", locale)}»`;
    const usesModel = trimmed.match(/^Uses (.+)\.$/);
    if (usesModel) return `Используется ${usesModel[1]}.`;
    const detected = trimmed.match(/^Detected: (.+)$/);
    if (detected) return `Обнаружено: ${detected[1]}`;
    const foundCalendars = trimmed.match(/^Found (\d+) calendars?$/);
    if (foundCalendars) {
      const count = Number(foundCalendars[1]);
      const word = count % 10 === 1 && count % 100 !== 11
        ? "календарь"
        : [2, 3, 4].includes(count % 10) && ![12, 13, 14].includes(count % 100)
          ? "календаря"
          : "календарей";
      return `Найдено: ${count} ${word}`;
    }
  }

  if (locale === "en") {
    const version = trimmed.match(/^Версия (.+)$/);
    if (version) return `Version ${version[1]}`;
    const usedMb = trimmed.match(/^Использовано (.+) МБ$/);
    if (usedMb) return `${usedMb[1]} MB used`;
  }

  return null;
}

export function normalizeLocale(value: string | null | undefined): AppLocale | null {
  return value === "en" || value === "ru" ? value : null;
}

export function getInitialLocale(): AppLocale {
  return normalizeLocale(localStorage.getItem("ui_locale")) ?? DEFAULT_LOCALE;
}

export function translateText(value: string, locale: AppLocale): string {
  const trimmed = value.trim();
  if (!trimmed) return value;

  const pattern = translatePattern(trimmed, locale);
  if (pattern) return preserveOuterWhitespace(value, pattern);

  const exact = locale === "ru" ? ru[trimmed] : enOverrides[trimmed] ?? reverseRu[trimmed];
  if (exact) return preserveOuterWhitespace(value, exact);

  if (locale === "ru" && trimmed.includes("Velo")) {
    return value.replaceAll("Velo Mail", APP_NAME_RU).replaceAll("Velo", APP_NAME_RU);
  }
  if (locale === "en" && trimmed.includes("Velo")) {
    return value.replaceAll("Velo Mail", APP_NAME_EN).replaceAll("Velo", APP_NAME_EN);
  }
  if (locale === "en" && trimmed.includes("Офис360")) {
    return value.replaceAll("Офис360", APP_NAME_EN);
  }

  return value;
}
